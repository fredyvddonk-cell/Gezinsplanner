let state = loadSavedState();

if (!Array.isArray(state.recipes)) state.recipes = [];
if (!Array.isArray(state.shopping)) state.shopping = [];
if (!Array.isArray(state.suppressedStockShopping)) state.suppressedStockShopping = [];

state.shopping.forEach((item) => {
  if (item.quantity === undefined) item.quantity = 1;
  if (item.weight === undefined) item.weight = "";
  if (item.weightUnit === undefined) item.weightUnit = "";
});

if (!Array.isArray(state.meals)) state.meals = [];
if (!Array.isArray(state.freezer)) state.freezer = [];
if (!Array.isArray(state.hutsel)) state.hutsel = [];
if (!Array.isArray(state.stock))
  state.stock = stockCatalog.map((x) => ({ ...x }));


defaultRecipes.forEach((recipe) => {
  const exists = state.recipes.some(
    (r) =>
      r.id === recipe.id ||
      String(r.name).trim().toLowerCase() === recipe.name.trim().toLowerCase(),
  );
  if (!exists) state.recipes.push(JSON.parse(JSON.stringify(recipe)));
});
if (!Array.isArray(state.categories)) {
  state.categories = [
    ...new Set([
      ...defaultCategories,
      ...state.stock.map((x) => x.category || "Overig"),
    ]),
  ];
}
const stockNameMap = new Map(
  state.stock.map((item) => [String(item.name).trim().toLowerCase(), item.id]),
);
const recipeStockAliases = {
  bouillontablet: "bouillonblokjes groente",
  "jong belegen kaas": "jong belegen kaas",
  "rode paprika": "paprika",
  appels: "appels",
  mayonaise: "mayonaise",
  uienpoeder: "uienpoeder",
  knoflookpoeder: "knoflookpoeder",
  kaneel: "kaneel",
  citroensap: "citroensap",
};

state.meals.forEach((meal) => {
  if (meal.recipeId) return;
  const match = state.recipes.find(
    (r) =>
      String(r.name || "")
        .trim()
        .toLowerCase() ===
      String(meal.name || "")
        .trim()
        .toLowerCase(),
  );
  if (match) meal.recipeId = match.id;
});
state.recipes.forEach((recipe) => {
  (recipe.ingredients || []).forEach((ingredient) => {
    if (ingredient.stockId) return;
    const key = String(ingredient.name || "")
      .trim()
      .toLowerCase();
    const direct = stockNameMap.get(key);
    const alias = recipeStockAliases[key]
      ? stockNameMap.get(recipeStockAliases[key])
      : null;
    ingredient.stockId = direct || alias || null;
  });
});
state.stock.forEach((x) => {
  if (!x.packageType) x.packageType = "verpakking";
  if (x.packageContent === undefined) x.packageContent = 0;
  if (!x.unit) x.unit = "gram";
  if (x.currentAmount === undefined) {
    const n = parseFloat(String(x.amount || "").replace(",", "."));
    x.currentAmount = Number.isFinite(n) ? n : 0;
  }
  if (x.minimum === undefined) x.minimum = 0;
  if (x.toHutsel === undefined) x.toHutsel = false;
  if (x.buyCount === undefined) x.buyCount = "";
  if (x.category === undefined) x.category = "Overig";
  if (!x.stockType) x.stockType = "simple";
  if (!x.simpleStatus) x.simpleStatus = "Voldoende";
});
const existingStockNames = new Set(
  state.stock.map((x) => String(x.name).trim().toLowerCase()),
);
stockCatalog.forEach((item) => {
  if (!existingStockNames.has(item.name.trim().toLowerCase()))
    state.stock.push({ ...item, id: Date.now() + item.id });
});
