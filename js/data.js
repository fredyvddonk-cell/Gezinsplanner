function restoreRestorePoint() {
  const raw = localStorage.getItem(RESTORE_KEY);
  if (!raw) {
    alert("Er is nog geen herstelpunt.");
    return;
  }
  if (
    !confirm(
      "Wil je teruggaan naar het laatst bewaarde herstelpunt? De huidige wijzigingen worden vervangen.",
    )
  )
    return;
  try {
    const restored = JSON.parse(raw);
    if (!restored || typeof restored !== "object")
      throw new Error("Ongeldig herstelpunt");
    state = restored;
    persistState();
    renderAll();
    go("start");
    updateRestoreStatus();
    alert("Herstelpunt teruggezet.");
  } catch (error) {
    console.error("Herstellen mislukt:", error);
    alert("Het herstelpunt kon niet worden teruggezet.");
  }
}

function updateRestoreStatus() {
  const el = document.getElementById("backupStatus");
  if (!el) return;
  const stamp = localStorage.getItem(RESTORE_META_KEY);
  if (!stamp) {
    el.textContent = "Nog geen herstelpunt gemaakt.";
    return;
  }
  const date = new Date(stamp);
  el.textContent = `Laatst bewaard: ${date.toLocaleDateString("nl-NL")} om ${date.toLocaleTimeString("nl-NL", { hour: "2-digit", minute: "2-digit" })}`;
}

